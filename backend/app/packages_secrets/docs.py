README = """# Secrets Store Package

Optional package boundary for OMH secure configuration references.

It enables the Secrets Store UI entry, production readiness checks and package
visibility for installations that want to manage credentials from OMH instead
of placing secrets in connector JSON or environment-specific documents.
"""

QUICK_START = """# Quick Start

1. Install the Secrets Store package from Plugin Store.
2. Open Secrets from the sidebar.
3. Create a secret reference and use `secret://<key>` in connector settings.
4. Rotate secrets from the Secrets page when credentials change.
"""
