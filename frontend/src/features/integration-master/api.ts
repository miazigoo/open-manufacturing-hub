import { request } from '../../api/client';
import type {
  CompileDraftRequest,
  CompileDraftResponse,
  CompileDraftValidationResponse,
  CompilePreviewResponse,
  CompiledEnableResponse,
  CompiledRunTestRequest,
  CompiledRunTestResponse,
  FinalActionConfig,
  FinalActionPreviewResponse,
  FinalActionRequest,
  FinalActionSaveResponse,
  FinalActionTestRequest,
  FinalActionTestResponse,
  FinalActionValidationResponse,
  ForeachODataStepConfig,
  ForeachODataStepPreviewResponse,
  ForeachODataStepRequest,
  ForeachODataStepSaveResponse,
  ForeachODataStepTestResponse,
  ForeachODataStepValidationResponse,
  InputContract,
  InputContractValidationResponse,
  InputDraftSaveResponse,
  InputParseRequest,
  InputParseResponse,
  IntegrationScenario,
  ODataObjectStepConfig,
  ODataObjectStepPreviewResponse,
  ODataObjectStepRequest,
  ODataObjectStepSaveResponse,
  ODataObjectStepTestResponse,
  ODataObjectStepValidationResponse,
  ODataStepConfig,
  ODataStepPreviewResponse,
  ODataStepRequest,
  ODataStepSaveResponse,
  ODataStepTestResponse,
  ODataStepValidationResponse,
  PayloadStepConfig,
  PayloadStepPreviewResponse,
  PayloadStepRequest,
  PayloadStepSaveResponse,
  PayloadStepValidationResponse,
} from './types';

export const integrationMasterApi = {
  scenarios: () => request<IntegrationScenario[]>('/api/integration-master/scenarios'),
  parse: (payload: InputParseRequest) => request<InputParseResponse>('/api/integration-master/input/parse', { method: 'POST', body: JSON.stringify(payload) }),
  validate: (contract: InputContract) => request<InputContractValidationResponse>('/api/integration-master/input/validate', { method: 'POST', body: JSON.stringify({ contract }) }),
  saveDraft: (contract: InputContract, parseResult?: InputParseResponse | null) => request<InputDraftSaveResponse>('/api/integration-master/input/save-draft', { method: 'POST', body: JSON.stringify({ contract, parse_result: parseResult ?? null }) }),
  validateODataStep: (payload: ODataStepRequest) => request<ODataStepValidationResponse>('/api/integration-master/odata-step/validate', { method: 'POST', body: JSON.stringify(payload) }),
  previewODataStep: (payload: ODataStepRequest) => request<ODataStepPreviewResponse>('/api/integration-master/odata-step/preview', { method: 'POST', body: JSON.stringify(payload) }),
  testODataStep: (payload: ODataStepRequest) => request<ODataStepTestResponse>('/api/integration-master/odata-step/test', { method: 'POST', body: JSON.stringify(payload) }),
  saveODataStep: (draftId: string, inputContract: InputContract, step: ODataStepConfig) =>
    request<ODataStepSaveResponse>(`/api/integration-master/drafts/${draftId}/odata-steps`, { method: 'POST', body: JSON.stringify({ input_contract: inputContract, odata_step: step }) }),
  validateODataObjectStep: (payload: ODataObjectStepRequest) => request<ODataObjectStepValidationResponse>('/api/integration-master/odata-object-step/validate', { method: 'POST', body: JSON.stringify(payload) }),
  previewODataObjectStep: (payload: ODataObjectStepRequest) => request<ODataObjectStepPreviewResponse>('/api/integration-master/odata-object-step/preview', { method: 'POST', body: JSON.stringify(payload) }),
  testODataObjectStep: (payload: ODataObjectStepRequest) => request<ODataObjectStepTestResponse>('/api/integration-master/odata-object-step/test', { method: 'POST', body: JSON.stringify(payload) }),
  saveODataObjectStep: (draftId: string, inputContract: InputContract, previousVariables: Record<string, unknown>, step: ODataObjectStepConfig) =>
    request<ODataObjectStepSaveResponse>(`/api/integration-master/drafts/${draftId}/odata-object-steps`, { method: 'POST', body: JSON.stringify({ input_contract: inputContract, previous_variables: previousVariables, odata_object_step: step }) }),
  validateForeachODataStep: (payload: ForeachODataStepRequest) => request<ForeachODataStepValidationResponse>('/api/integration-master/foreach-odata-step/validate', { method: 'POST', body: JSON.stringify(payload) }),
  previewForeachODataStep: (payload: ForeachODataStepRequest) => request<ForeachODataStepPreviewResponse>('/api/integration-master/foreach-odata-step/preview', { method: 'POST', body: JSON.stringify(payload) }),
  testForeachODataStep: (payload: ForeachODataStepRequest) => request<ForeachODataStepTestResponse>('/api/integration-master/foreach-odata-step/test', { method: 'POST', body: JSON.stringify(payload) }),
  saveForeachODataStep: (draftId: string, inputContract: InputContract, previousVariables: Record<string, unknown>, step: ForeachODataStepConfig) =>
    request<ForeachODataStepSaveResponse>(`/api/integration-master/drafts/${draftId}/foreach-odata-steps`, { method: 'POST', body: JSON.stringify({ input_contract: inputContract, previous_variables: previousVariables, foreach_step: step }) }),
  validatePayloadStep: (payload: PayloadStepRequest) => request<PayloadStepValidationResponse>('/api/integration-master/payload/validate', { method: 'POST', body: JSON.stringify(payload) }),
  previewPayloadStep: (payload: PayloadStepRequest) => request<PayloadStepPreviewResponse>('/api/integration-master/payload/preview', { method: 'POST', body: JSON.stringify(payload) }),
  savePayloadStep: (draftId: string, inputContract: InputContract, previousVariables: Record<string, unknown>, step: PayloadStepConfig) =>
    request<PayloadStepSaveResponse>(`/api/integration-master/drafts/${draftId}/payload-steps`, { method: 'POST', body: JSON.stringify({ input_contract: inputContract, previous_variables: previousVariables, payload_step: step }) }),
  validateFinalAction: (payload: FinalActionRequest) => request<FinalActionValidationResponse>('/api/integration-master/final-action/validate', { method: 'POST', body: JSON.stringify(payload) }),
  previewFinalAction: (payload: FinalActionRequest) => request<FinalActionPreviewResponse>('/api/integration-master/final-action/preview', { method: 'POST', body: JSON.stringify(payload) }),
  testFinalAction: (payload: FinalActionTestRequest) => request<FinalActionTestResponse>('/api/integration-master/final-action/test', { method: 'POST', body: JSON.stringify(payload) }),
  saveFinalAction: (draftId: string, inputContract: InputContract, previousVariables: Record<string, unknown>, finalAction: FinalActionConfig) =>
    request<FinalActionSaveResponse>(`/api/integration-master/drafts/${draftId}/final-action`, { method: 'POST', body: JSON.stringify({ input_contract: inputContract, previous_variables: previousVariables, final_action: finalAction }) }),
  validateForCompile: (draftId: string) => request<CompileDraftValidationResponse>(`/api/integration-master/drafts/${draftId}/validate-for-compile`, { method: 'POST' }),
  compilePreview: (draftId: string) => request<CompilePreviewResponse>(`/api/integration-master/drafts/${draftId}/compile-preview`, { method: 'POST' }),
  compileDraft: (draftId: string, payload: CompileDraftRequest) => request<CompileDraftResponse>(`/api/integration-master/drafts/${draftId}/compile`, { method: 'POST', body: JSON.stringify(payload) }),
  runCompiledTest: (integrationFlowId: string, payload: CompiledRunTestRequest) => request<CompiledRunTestResponse>(`/api/integration-master/compiled/${integrationFlowId}/run-test`, { method: 'POST', body: JSON.stringify(payload) }),
  enableCompiled: (integrationFlowId: string) => request<CompiledEnableResponse>(`/api/integration-master/compiled/${integrationFlowId}/enable`, { method: 'POST' }),
};
