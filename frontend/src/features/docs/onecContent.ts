    '- `lookup.*` - OData запросы, фильтры, найденные бизнес-объекты.',
    '- `transform.output` - финальный JSON/XML/ZPL перед target.',
    '- `target.request` и `target.response` - запрос и ответ целевой системы.',
    '- `external.error` - оригинальная ошибка 1C/API/принтера без упрощения текста.',
