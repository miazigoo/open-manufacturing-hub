function md(...lines: string[]) {
  return lines.join('\n').trim();
}

function page(sectionId: string, slug: string, title: string, description: string, order: number, markdown: string): PageSeed {
  return { packageId: 'onec', sectionId, slug, title, description, order, markdown };
}

type ScenarioConfig = {
  slug: string;
  title: string;
  description: string;
  order: number;
  goal: string;
  when: string[];
  diagram: string;
  endpoint: string;
  payloadLanguage: string;
  payload: string[];
  target: string[];
  success: string[];
  errors: string[];
  related: string[];
  screenshots: string[];
  exampleId?: string;
  openPages?: Array<{ route: string; label: string }>;
};

function scenario(config: ScenarioConfig): PageSeed {
  return page('scenarios', config.slug, config.title, config.description, config.order, md(
    `# ${config.title}`,
    '',
    '## 1. Что делает сценарий',
    config.goal,
    '',
    '## 2. Когда использовать',
    ...config.when.map((item) => `- ${item}`),
    '',
    '## 3. Схема обмена',
    '```text',
    config.diagram,
    '```',
    '',
    ...config.screenshots.map((item) => item.includes('.') ? `::screenshot{assetId="${item}"}` : `{{screenshot:${item}}}`),
    ...(config.openPages ?? []).map((item) => `::open-page{route="${item.route}" label="${item.label}"}`),
    '',
    '## 4. Что настроить заранее',
    '- 1C Package установлен и enabled в `/plugin-store`.',
    '- 1C connector создан в `/connectors` и проходит healthcheck.',
    '- Endpoint создан в `/integration-bus` или Flow опубликован из `/integration-flows`.',
    '- Секреты хранятся через Secrets Store, а не в JSON конфиге.',
    '- Для async-режима включена очередь, retry policy и DLQ.',
    '',
    '## 5. Куда отправлять из 1C',
    '```text',
    config.endpoint,
    '```',
    '',
    'Рекомендуемые заголовки:',
    '```text',
    'Content-Type: application/json или application/xml',
    'X-OMH-Token: <static inbound token, если endpoint закрыт token auth>',
    'X-OMH-Source: 1c',
    'X-OMH-Trace-Id: <GUID из 1C или созданный OMH>',
    '```',
    '',
    '## 6. Что отправить',
    `\`\`\`${config.payloadLanguage}`,
    ...config.payload,
    '```',
    ...(config.exampleId ? ['', `::example{exampleId="${config.exampleId}"}`] : []),
    '',
    '## 7. Минимальный пример 1C-кода',
    '```1c',
    'HTTP = Новый HTTPСоединение("omh.example.local", 443,,,, Новый ЗащищенноеСоединениеOpenSSL);',
    `Запрос = Новый HTTPЗапрос("${config.endpoint.replace('POST ', '')}");`,
    'Запрос.Заголовки.Вставить("Content-Type", "application/json");',
    'Запрос.Заголовки.Вставить("X-OMH-Token", "<token>");',
    'Запрос.УстановитьТелоИзСтроки(ТелоЗапроса, КодировкаТекста.UTF8);',
    'Ответ = HTTP.ОтправитьДляОбработки(Запрос);',
    'Если Ответ.КодСостояния >= 300 Тогда',
    '  ВызватьИсключение "OMH вернул ошибку: " + Ответ.ПолучитьТелоКакСтроку();',
    'КонецЕсли;',
    '```',
    '',
    '## 8. Что OMH делает по шагам',
    '1. Проверяет package gate, endpoint matcher, token/auth и content type.',
    '2. Создает event и сохраняет исходный request как входной artifact.',
    '3. Запускает flow или route: lookup, transform, resolver, business rules.',
    '4. Выполняет target request с timeout, retry policy и redaction секретов.',
    '5. Сохраняет outgoing request, target response, external error и итоговый статус.',
    '6. Для async-режима переводит неуспешные попытки в retry_waiting или DLQ.',
    '',
    '## 9. Что OMH отправляет дальше',
    '```text',
    ...config.target,
    '```',
    '',
    '## 10. Что получает 1C в ответ',
    '```json',
    ...config.success,
    '```',
    '',
    '## 11. Timeline и artifacts',
    '- `incoming.request` - исходное тело из 1C без потери формата.',
    '- `route.match` - выбранный endpoint, matcher и режим выполнения.',
    '- `lookup.*` - OData запросы, фильтры, найденные бизнес-объекты.',
    '- `transform.output` - финальный JSON/XML/ZPL перед target.',
    '- `target.request` и `target.response` - запрос и ответ целевой системы.',
    '- `external.error` - оригинальная ошибка 1C/API/принтера без упрощения текста.',
    '',
    '## 12. Ошибки, retry и исправление',
    ...config.errors.map((item) => `- ${item}`),
    '- После исправления данных используйте `Retry now` на событии или `Edit retry`, если нужно поправить payload.',
    '- Если событие в DLQ, сначала откройте original error и artifacts, затем выберите `Replay from DLQ`.',
    '- Если ошибка в конфигурации connector/flow, выпустите новую версию config и повторите event.',
    '',
    '## 13. Связанные страницы',
    ...config.related.map((item) => `- ${relatedLink(item)}`),
  ));
}

function relatedLink(item: string) {
  const route = /^`([^`]+)`$/.exec(item)?.[1];
  return route ? `[${route}](${route})` : item;
}

