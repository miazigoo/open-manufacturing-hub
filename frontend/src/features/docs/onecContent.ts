    'Ответ = HTTP.ОтправитьДляОбработки(Запрос);',
    'Если Ответ.КодСостояния >= 300 Тогда',
    '  ВызватьИсключение "OMH вернул ошибку: " + Ответ.ПолучитьТелоКакСтроку();',
    'КонецЕсли;',
    '```',
    '',
    '## 8. Что OMH делает по шагам',
    '1. Проверяет package gate, endpoint matcher, token/auth и content type.',
    '2. Создает event и сохраняет исходный request как входной artifact.',
    '3. Запускает flow или route: lookup, transform, resolver, business rules.',
    '4. Выполняет target request с timeout, retry policy и redaction секретов.',
    '5. Сохраняет outgoing request, target response, external error и итоговый статус.',
    '6. Для async-режима переводит неуспешные попытки в retry_waiting или DLQ.',
